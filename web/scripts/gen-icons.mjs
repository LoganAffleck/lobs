// Turns native/icons/*.svg (the Lucide set the app ships) into one TS module, so the web UI
// draws exactly the glyphs the app does, with no icon package and no import.meta.glob
// (Canvas can't cache builds that use it).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const src = join(here, '../../native/icons')
const out = join(here, '../src/ui/icons.gen.ts')

const icons = {}
for (const f of readdirSync(src).filter((f) => f.endsWith('.svg')).sort()) {
  const svg = readFileSync(join(src, f), 'utf8')
  // Keep the child elements only; the wrapper's stroke settings are applied by <Icon>.
  const body = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
  icons[f.replace(/\.svg$/, '')] = body.replace(/\s*\n\s*/g, '').trim()
}
const lines = Object.entries(icons).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
writeFileSync(
  out,
  `// Generated by scripts/gen-icons.mjs from native/icons (Lucide, ISC). Don't edit.\n` +
    `export const ICONS = {\n${lines.join('\n')}\n} as const\n\nexport type IconName = keyof typeof ICONS\n`,
)
console.log(`${Object.keys(icons).length} icons -> src/ui/icons.gen.ts`)
